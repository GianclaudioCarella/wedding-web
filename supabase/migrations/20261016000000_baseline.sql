--
-- Name: v_tavily_metrics; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_tavily_metrics AS
 SELECT date_trunc('hour'::text, "timestamp") AS hour,
    count(*) AS total_calls,
    count(*) FILTER (WHERE (success = true)) AS successful_calls,
    count(*) FILTER (WHERE (success = false)) AS failed_calls,
    (avg(response_time_ms))::integer AS avg_response_time_ms,
    max(response_time_ms) AS max_response_time_ms
   FROM public.api_logs
  WHERE ((api_name = 'tavily'::text) AND ("timestamp" >= (now() - '7 days'::interval)))
  GROUP BY (date_trunc('hour'::text, "timestamp"))
  ORDER BY (date_trunc('hour'::text, "timestamp")) DESC;


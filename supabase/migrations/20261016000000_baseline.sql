--
-- Name: reorder_checklist_items(uuid, uuid[]); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.reorder_checklist_items(list_id uuid, item_ids uuid[]) RETURNS void
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
BEGIN
  IF cardinality(item_ids) IS NULL
     OR cardinality(item_ids) <> (SELECT count(DISTINCT id) FROM unnest(item_ids) AS ids(id)) THEN
    RAISE EXCEPTION 'Invalid checklist order';
  END IF;

  UPDATE public.checklist_items AS item
  SET position = ordered.ordinality::integer - 1
  FROM unnest(item_ids) WITH ORDINALITY AS ordered(id, ordinality)
  WHERE item.id = ordered.id AND item.checklist_id = list_id;
END;
$$;

--
-- Name: search_document_chunks(public.vector, double precision, integer); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.search_document_chunks(query_embedding public.vector, match_threshold double precision DEFAULT 0.5, match_count integer DEFAULT 5) RETURNS TABLE(chunk_id uuid, document_id uuid, content text, distance double precision, metadata jsonb, document_filename text)
    LANGUAGE plpgsql
    AS $$
BEGIN
  RETURN QUERY
  SELECT
    dc.id as chunk_id,
    dc.document_id,
    dc.content,
    (dc.embedding <=> query_embedding) as distance,
    dc.metadata,
    d.filename as document_filename
  FROM document_chunks dc
  JOIN documents d ON dc.document_id = d.id
  WHERE d.status = 'completed'
    AND (dc.embedding <=> query_embedding) < match_threshold
  ORDER BY dc.embedding <=> query_embedding
  LIMIT match_count;
END;
$$;

